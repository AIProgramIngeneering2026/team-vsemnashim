    internal static ItemKind Classify(string id)
    {
        if (!uint.TryParse(id, NumberStyles.None, CultureInfo.InvariantCulture, out var number))
            return ItemKind.Unknown;
        if (Abilities.Contains(number))
            return ItemKind.Ability;
        return ShopItems.Contains(number) ? ItemKind.Shop : ItemKind.Unknown;
    }
